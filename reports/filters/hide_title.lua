-- Pandoc Lua-фильтр для report.Rmd.
-- Заголовок из YAML (title) нужен как метаданные документа, но титульный лист
-- по требованиям СПбГУТ оформляется вручную (в теле отчёта), поэтому
-- автоматический блок «Title» в начале документа скрываем.
function Meta(meta)
  meta.title = nil
  return meta
end
